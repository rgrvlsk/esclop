#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-3.0-or-later
#
# Writes the notices for the Swift packages statically linked into L'Esclop's own executables:
# one table row per Package.resolved pin (identity, version, licence, source) and each package's
# licence text, taken from its checkout in .build/checkouts.
#
#   Scripts/swift-notices.sh OUT.md
#
# Run after `swift build` (or `swift package resolve`). The licence column is a best-effort SPDX
# identification of the text; "UNKNOWN" makes Scripts/licence-gate.sh --dist fail, so a new
# dependency under an unrecognised licence is looked at by a person.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT=${1:?usage: Scripts/swift-notices.sh OUT.md}
RESOLVED="$ROOT/Package.resolved"
CHECKOUTS="$ROOT/.build/checkouts"
[ -f "$RESOLVED" ] || { echo "swift-notices: no Package.resolved" >&2; exit 1; }

identify() { # licence file -> SPDX expression
  local f=$1 ids=""
  if grep -q 'Apache License' "$f" && grep -q 'Version 2.0' "$f"; then ids="Apache-2.0"; fi
  if grep -q 'Permission is hereby granted, free of charge' "$f"; then ids="${ids:+$ids AND }MIT"; fi
  if grep -q 'Redistribution and use in source and binary forms' "$f"; then
    if grep -q 'Neither the name' "$f"; then ids="${ids:+$ids AND }BSD-3-Clause"; else ids="${ids:+$ids AND }BSD-2-Clause"; fi
  fi
  echo "${ids:-UNKNOWN}"
}

rows=""; texts=""; i=0
while id="$(plutil -extract "pins.$i.identity" raw -o - "$RESOLVED" 2>/dev/null)"; do
  url="$(plutil -extract "pins.$i.location" raw -o - "$RESOLVED")"
  ver="$(plutil -extract "pins.$i.state.version" raw -o - "$RESOLVED" 2>/dev/null ||
    plutil -extract "pins.$i.state.revision" raw -o - "$RESOLVED")"
  lic=""
  for cand in "$CHECKOUTS/$id"/LICENSE* "$CHECKOUTS/$id"/LICENCE* "$CHECKOUTS/$id"/COPYING* "$CHECKOUTS/$id"/license*; do
    [ -f "$cand" ] && { lic=$cand; break; }
  done
  if [ -z "$lic" ]; then
    echo "swift-notices: no licence file in .build/checkouts/$id (run swift build first)" >&2
    spdx=UNKNOWN
  else
    spdx="$(identify "$lic")"
    texts="$texts
## $id $ver

From \`$(basename "$lic")\` of $url

\`\`\`\`
$(cat "$lic")
\`\`\`\`
"
  fi
  rows="$rows| $id | $ver | $spdx | $url |
"
  i=$((i + 1))
done

mkdir -p "$(dirname "$OUT")"
{
  echo "# Third-party notices: Swift packages"
  echo
  echo "L'Esclop's own executables (the \`esclop\` command line and the app) are GPL-3.0-or-later and"
  echo "statically link the Swift packages below, pinned by \`Package.resolved\`. Generated by"
  echo "\`Scripts/swift-notices.sh\`."
  echo
  echo "| Package | Version | Licence | Source |"
  echo "| --- | --- | --- | --- |"
  printf '%s' "$rows"
  printf '%s' "$texts"
} > "$OUT"
echo "swift-notices: $i packages -> $OUT" >&2
